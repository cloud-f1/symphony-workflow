"""Epic -> Story/Task decomposition (ADLC-46).

Plan-phase-shaped, not Run/RunStore-shaped: read-only exploration via
`agent_runner.run_plan()`'s `permission_mode="plan"` wiring (same mechanism
`orchestrator.execute_plan()` uses, just with `prompts.PLAN_DECOMPOSE_SCHEMA`
in place of `PLAN_OUTPUT_SCHEMA`) — no repo writes, no Jira writes. This is
deliberately a standalone one-shot operation against an Epic, not routed
through `runs.Run`/`RunStore`: that state machine tracks a single issue's
Plan -> Implement lifecycle, which decompose has no equivalent of (see
CLAUDE.md's "Adding a new tool"/layering notes and the ADLC-46 ticket's
design guidance).

Renders `docs/runs/<epic-key>/decomposition.md` (human review) and
`decomposition.json` (the structured seam `sync-decomposition` reads to
create the real Jira Stories/Subtasks once a human has reviewed the markdown).
"""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, ValidationError

from symphony_workflow.agent_runner import run_plan
from symphony_workflow.client import JiraClient
from symphony_workflow.prompts import PLAN_DECOMPOSE_SCHEMA, render_decompose_prompt
from symphony_workflow.workspace import WorkspaceManager

DEFAULT_DECOMPOSE_MAX_TURNS = 10

# Templated from CLAUDE.md's own testing/lint/style standards (the "three
# non-negotiables" section plus "Code style" and "Adding a new tool") —
# deliberately NOT asked of the LLM as part of PLAN_DECOMPOSE_SCHEMA. Applies
# to every Story a decomposition produces; a per-story acceptance-criteria
# list is what the LLM is asked to generate instead (see
# prompts.DECOMPOSE_PROMPT_TEMPLATE).
DEFINITION_OF_DONE_TEMPLATE: list[str] = [
    "Unit tests added for all new/changed code; HTTP calls mocked with respx — "
    "no live Jira access in tests (CLAUDE.md “the three non-negotiables” #3).",
    "If a Jira operation was added or changed: a typed client.py method AND a "
    "matching tools.py Tool entry (pydantic args model), both reachable via "
    "`symphony-workflow list-tools`/`call` (CLAUDE.md “the three non-negotiables” #2).",
    "A Typer CLI subcommand added only if a human needs a friendly entry point for "
    "it — not every tool needs one (CLAUDE.md “Adding a new tool”, step 4).",
    "`uv run ruff check .` and `uv run ruff format --check .` both pass clean "
    "(CLAUDE.md “Code style”).",
    "`uv run pytest` passes in full (CLAUDE.md “the three non-negotiables” #3).",
    "Type hints on all new code; pydantic models for anything crossing a boundary "
    "such as an HTTP response or tool input (CLAUDE.md “Code style”).",
    "No bare `except Exception: pass`; typed exceptions (e.g. JiraError) caught "
    "specifically (CLAUDE.md “Code style”).",
    "No org-specific values (cloud-f1.atlassian.net, CF1 field IDs, ADLC, a "
    "hardcoded target-repo path) baked into client.py/orchestrator.py/poller.py — "
    "configuration goes through env vars (CLAUDE.md “What NOT to do here”).",
]


def assign_ids(decomposition: Decomposition) -> bool:
    """Fill in missing `id`s (`s<n>`, `s<n>.t<m>`, by position) and return whether anything
    changed. Existing ids are never touched, so ids stay stable when entries are reordered.
    """
    used = {s.id for s in decomposition.stories if s.id} | {
        t.id for s in decomposition.stories for t in s.tasks if t.id
    }
    changed = False

    def fresh(base: str) -> str:
        candidate, n = base, 1
        while candidate in used:
            n += 1
            candidate = f"{base}-{n}"
        used.add(candidate)
        return candidate

    for i, story in enumerate(decomposition.stories, start=1):
        if not story.id:
            story.id, changed = fresh(f"s{i}"), True
        for j, task in enumerate(story.tasks, start=1):
            if not task.id:
                task.id, changed = fresh(f"{story.id}.t{j}"), True
    return changed


class DecomposeError(RuntimeError):
    """Raised when the agent run doesn't yield usable structured `stories` output."""


class Task(BaseModel):
    # Optional stable id (ADLC-146), e.g. "s1.t2". Absent in files written before drift
    # detection existed; `drift.assign_ids` fills it in and writes it back.
    id: str | None = None
    title: str
    description: str


class Story(BaseModel):
    id: str | None = None  # e.g. "s1"; see Task.id
    title: str
    user_story: str
    acceptance_criteria: list[str]
    tasks: list[Task]


class Decomposition(BaseModel):
    epic_key: str
    stories: list[Story]
    definition_of_done: list[str]


def render_decomposition_markdown(decomposition: Decomposition) -> str:
    lines = [
        f"# Decomposition: {decomposition.epic_key}",
        "",
        f"Generated by `symphony-workflow decompose {decomposition.epic_key}` for human review. "
        "No Jira issues have been created from this yet — see ADLC-47 for turning a "
        "reviewed decomposition into real Jira Stories/Subtasks.",
        "",
    ]
    for i, story in enumerate(decomposition.stories, start=1):
        lines.append(f"## Story {i}: {story.title}")
        lines.append("")
        lines.append(f"**User story:** {story.user_story}")
        lines.append("")
        lines.append("**Acceptance criteria:**")
        for criterion in story.acceptance_criteria:
            lines.append(f"- {criterion}")
        lines.append("")
        lines.append("**Tasks:**")
        for task in story.tasks:
            lines.append(f"- **{task.title}** — {task.description}")
        lines.append("")
    lines.append("## Definition of Done")
    lines.append("")
    lines.append(
        "Applies to every Story above. Templated from this repo's own CLAUDE.md "
        "standards, not LLM-generated:"
    )
    lines.append("")
    for item in decomposition.definition_of_done:
        lines.append(f"- [ ] {item}")
    lines.append("")
    return "\n".join(lines)


async def execute_decompose(
    epic_key: str,
    *,
    client: JiraClient,
    workspaces: WorkspaceManager,
    runs_docs_root: Path,
    max_turns: int = DEFAULT_DECOMPOSE_MAX_TURNS,
) -> tuple[Decomposition, Path]:
    """Fetch the Epic, run the Plan-phase agent against it with
    `PLAN_DECOMPOSE_SCHEMA`, and render the result to
    `<runs_docs_root>/<epic_key>/decomposition.{md,json}`.

    Raises `JiraError` (bad epic key), `WorkspaceError` (worktree setup),
    `AgentRunError` (agent run failed), or `DecomposeError` (agent run
    succeeded but produced no usable structured `stories` output).
    """
    issue = client.get_issue(epic_key)
    workspace_path = workspaces.ensure(epic_key, branch_slug=issue.summary)

    prompt = render_decompose_prompt(issue)
    workspaces.run_before_run(epic_key, workspace_path)
    try:
        result = await run_plan(
            prompt,
            cwd=str(workspace_path),
            max_turns=max_turns,
            output_schema=PLAN_DECOMPOSE_SCHEMA,
        )
    finally:
        workspaces.run_after_run(epic_key, workspace_path)

    stories_raw = (result.structured or {}).get("stories")
    if not stories_raw:
        raise DecomposeError(
            f"Agent run for {epic_key} did not produce structured `stories` output"
        )

    try:
        decomposition = Decomposition.model_validate(
            {
                "epic_key": epic_key,
                "stories": stories_raw,
                "definition_of_done": DEFINITION_OF_DONE_TEMPLATE,
            }
        )
    except ValidationError as exc:
        raise DecomposeError(f"Structured output for {epic_key} failed validation: {exc}") from exc

    out_dir = runs_docs_root / epic_key
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "decomposition.json").write_text(
        decomposition.model_dump_json(indent=2), encoding="utf-8"
    )
    md_path = out_dir / "decomposition.md"
    md_path.write_text(render_decomposition_markdown(decomposition), encoding="utf-8")

    return decomposition, md_path
